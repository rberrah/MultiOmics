import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const raw=readFileSync(new URL('../src/lib/multiomics/public-game-evidence/measurements.json',import.meta.url),'utf8').trim();
assert.equal(createHash('sha256').update(raw).digest('hex'),'43b82d54402483e4da2bdfe43b097f10961bb3509213ebe9b268bc18887528d8','Exact independently extracted public archive payload');
const d=JSON.parse(raw);
assert.equal(d.airwayPairs.length,4);
assert.equal(new Set(d.airwayPairs.map(p=>p[0])).size,4);
assert.deepEqual(d.qCounts,[2940,4100,4947]);
assert.equal(d.nutrimousePoints.length,40);
assert.equal(new Set(d.nutrimousePoints.map(p=>p[0])).size,40);
assert.equal(d.heldoutScores.length,10);
const held=new Set(d.heldoutScores.map(p=>p[0]));
const train=d.nutrimousePoints.filter(p=>!held.has(p[0])).map(p=>p[1]);
const mean=train.reduce((a,b)=>a+b,0)/train.length;
const sd=Math.sqrt(train.reduce((a,b)=>a+(b-mean)**2,0)/(train.length-1));
assert.equal(train.length,30);
assert.ok(Math.abs(mean+.514)<1e-12);
assert.ok(Math.abs(sd-.2616341219969281)<1e-12);
for(const [id,z] of d.heldoutScores)assert.ok(Math.abs((d.nutrimousePoints.find(p=>p[0]===id)[1]-mean)/sd-z)<1e-10);
console.log('Public teaching data hash, pairing, BH thresholds and held-out projection: PASS');
