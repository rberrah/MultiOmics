#!/usr/bin/env python3
"""Verify the true isolated MOFA2/Basilisk environment. Standard library only."""
import hashlib
import json
import os
from pathlib import Path
import re
import sys

LOCK_PATH = Path("multiomics-engine/environment/mofa-python-pins.json")


def validate(lock, evidence, expected_commit=None):
    if lock.get("schema") != "multiomics.mofa-basilisk-python.v1":
        raise ValueError("Unknown Python lock schema")
    if lock.get("strictPythonLockReady") is not True:
        raise ValueError("The observed Python environment is not locked")
    if evidence.get("schema") != "multiomics.mofa-basilisk-provenance.v1":
        raise ValueError("Invalid actual runtime evidence schema")
    if evidence.get("runMode") != "verify" or evidence.get("strictLockVerified") is not True:
        raise ValueError("The R/Basilisk verifier did not enforce the environment lock")
    if "basiliskStart(" not in evidence.get("source", ""):
        raise ValueError("This is not isolated MOFA2 Basilisk evidence")
    if expected_commit and evidence.get("sourceCommit") != expected_commit:
        raise ValueError("Scientific evidence was generated by another source commit")
    if evidence.get("rPackageVersion") != lock.get("mofaRVersion"):
        raise ValueError("MOFA2 R version differs")
    if evidence.get("pythonVersion") != lock.get("pythonVersion"):
        raise ValueError("Exact Python interpreter version differs")
    if evidence.get("mofapy2Version") != lock.get("mofapy2Target"):
        raise ValueError("mofapy2 version differs")
    rows = evidence.get("installedPythonPackages")
    if not isinstance(rows, list) or not rows:
        raise ValueError("Missing installed Basilisk Python packages")
    packages = {}
    for row in rows:
        if not isinstance(row, dict) or set(row) != {"name", "version"}:
            raise ValueError("Malformed Python distribution evidence")
        name, version = row["name"], row["version"]
        if not isinstance(name, str) or re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) is None:
            raise ValueError("Unnormalized Python distribution name")
        if not isinstance(version, str) or not version or "\n" in version or "=" in version:
            raise ValueError("Invalid Python distribution version")
        if name in packages:
            raise ValueError("Duplicate normalized Python distribution name")
        packages[name] = version
    canonical = "".join(f"{name}={packages[name]}\n" for name in sorted(packages))
    checksum = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    if packages != lock.get("pinnedPackages"):
        raise ValueError("Python distribution or exact version drift")
    if len(packages) != lock.get("packageCount") or evidence.get("installedPackageCount") != len(packages):
        raise ValueError("Unexpected Python dependency closure size")
    if checksum != lock.get("fullPythonLibrarySha256"):
        raise ValueError("Computed Basilisk SHA-256 does not match the pinned source")
    if evidence.get("installedPythonLibrarySha256") != checksum:
        raise ValueError("Basilisk evidence SHA-256 was altered")
    return checksum


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python3 scripts/verify_mofa_basilisk_evidence.py <actual-evidence.json>")
    lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
    evidence = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    checksum = validate(lock, evidence, expected_commit=os.environ.get("GITHUB_SHA"))
    print("PASS: real strict MOFA2/Basilisk Python closure matches SHA-256", checksum)
